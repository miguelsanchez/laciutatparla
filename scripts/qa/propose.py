#!/usr/bin/env python3
"""Turn verified findings into the qa-data PR (arquitectura-agentes.md §6.3, F1.2–F1.3).

Deterministic, no LLM. Works in the persistent QA worktree (default ../lcp-qa), never in the
main checkout:

  1. Creates the worktree once (`git worktree add`), then fetches.
  2. Checks out the branch of the open qa-data PR (ingest/* or qa/*) or starts qa/YYYY-MM from
     origin/main: there is at most one data PR open in total.
  3. For each proposal, highest severity first, up to 10 live ones per PR: appends its entry
     to data/corrections/*.yml, checks the file with N7, and commits it (one commit per
     finding). The rest goes to $LCP_QA_STATE/queue.jsonl and is taken first next time.
  4. --push: pushes the branch and opens the PR with label qa-data, or updates the open one.

Only data/corrections/*.yml and meta/qa/proposals.json change; derived data is regenerated by
/apply-approved after your confirmation.

    "$PY" scripts/qa/propose.py --input proposals.json --dry-run   # commits locally, prints the body
    "$PY" scripts/qa/propose.py --fixture --dry-run                 # built-in example, branch qa/test
    "$PY" scripts/qa/propose.py --input proposals.json --push

Input: a JSON list of {fp, check, severity, subject, title, message, evidence, file, section?, entry,
op?}. op "append" (default) adds an entry; op "replace" swaps the existing entry with the same key
(for instance a patch that needs one more field) — the entry given is the complete new version; op
"delete" removes the existing entry with the same key (one a merge left dead) — the entry needs only
its key.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from qa import proposals as P  # noqa: E402
from qa.model import REPO_ROOT, Context, state_dir  # noqa: E402

FIXTURE = [{
    "fp": "TEST-fixture0001", "check": "TEST", "severity": "P2", "subject": "2026-07-23-001",
    "title": "Fixture proposal (test only)", "message": "Built-in example used by --fixture.",
    "evidence": {"file": "data/raw/texts/2026-07-23.txt", "quote": None},
    "file": "patches.yml", "section": None,
    "entry": {"iv_id": "2026-07-23-001", "fields": {"punts_ordre_dia": "fixture"},
              "reason": "propose.py fixture, never merged"},
}]


def default_worktree() -> Path:
    return Path(os.environ.get("LCP_QA_WORKTREE") or REPO_ROOT.parent / "lcp-qa").resolve()


def ensure_worktree(wt: Path, sparse: bool) -> None:
    if (wt / ".git").exists():
        return
    print(f"creating the QA worktree at {wt}")
    if sparse:  # tests: skip the 1.2 GB of PDFs and texts
        P.run(["git", "worktree", "add", "--no-checkout", "--detach", str(wt), "origin/main"], cwd=REPO_ROOT)
        P.run(["git", "sparse-checkout", "set", "--no-cone", "/*", "!/data/raw/pdfs/", "!/data/raw/texts/"], cwd=wt)
        P.run(["git", "checkout", "--detach", "origin/main"], cwd=wt)
    else:
        P.run(["git", "worktree", "add", "--detach", str(wt), "origin/main"], cwd=REPO_ROOT)


def checkout_branch(wt: Path, branch: str, fresh: bool = False) -> None:
    """Check out `branch` in the worktree: from origin/main when `fresh` (a new data PR), else from
    its remote copy (the branch of the open data PR, which must exist)."""
    if P.run(["git", "status", "--porcelain", "--untracked-files=no"], cwd=wt):
        raise SystemExit(f"{wt} has uncommitted changes: refusing to switch branch")
    remote = P.run(["git", "ls-remote", "--heads", "origin", branch], cwd=wt, check=False)
    start = "origin/main" if fresh or not remote else f"origin/{branch}"
    P.run(["git", "switch", "-q", "-C", branch, start], cwd=wt)


def free_branch_name(wt: Path, base: str) -> str:
    """qa/2026-10, else qa/2026-10-2, -3…: never reuse a branch that already exists on origin.

    With "rebase and merge" a merged PR leaves its branch behind, holding the original commits
    (main has copies with other hashes): building on it again would drag them into the new PR."""
    taken = {line.split("refs/heads/", 1)[1]
             for line in P.run(["git", "ls-remote", "--heads", "origin", f"{base}*"], cwd=wt, check=False).splitlines()
             if "refs/heads/" in line}
    if base not in taken:
        return base
    n = 2
    while f"{base}-{n}" in taken:
        n += 1
    return f"{base}-{n}"


def load_queue(state: Path) -> list[dict]:
    q = state / "queue.jsonl"
    if not q.exists():
        return []
    items = [json.loads(l) for l in q.read_text().splitlines() if l.strip()]
    q.unlink()
    return items


def save_queue(state: Path, items: list[dict]) -> None:
    if not items:
        return
    state.mkdir(parents=True, exist_ok=True)
    with open(state / "queue.jsonl", "a") as fh:
        for it in items:
            fh.write(json.dumps(it, ensure_ascii=False) + "\n")


def n7_errors(wt: Path, file: str, key: str) -> list[str]:
    """N7 findings on the entry just appended. P3 counts too: the pre-commit hook blocks any new
    finding, and a commit it refuses would stop the whole batch (a new entity whose intervention
    the verifier dropped is a P3 "has no effect")."""
    from qa import run_checks
    from qa.model import REGISTRY
    run_checks.load_checks()
    out = []
    for f in REGISTRY["N7"].fn(Context(wt / "data", repo_root=wt)):
        if f.subject == f"{file}|{key}":
            out.append(f"{f.key}: {f.message}")
    return out


def add_proposals(wt: Path, doc: dict, incoming: list[dict],
                  cap: int | None = None) -> tuple[list[dict], list[dict]]:
    """Append and commit; return (added, overflow)."""
    seen = {p["fp"] for p in doc["proposals"]}
    # Within a severity, entity-creating entries go last: each commit passes the pre-commit hook on
    # its own, and N7 only accepts a new entity once an intervention in the branch uses it.
    incoming = sorted((p for p in incoming if p["fp"] not in seen),
                      key=lambda p: (P.SEVERITY_ORDER.get(p["severity"], 9),
                                     p.get("file") in ("new_entities.yml", "variant_map_forced.yml")))
    added, overflow = [], []
    corrections = wt / "data" / "corrections"
    for prop in incoming:
        if len(P.active(doc)) >= (cap or P.MAX_PER_PR):
            overflow.append(prop)
            continue
        entry = dict(prop["entry"])
        entry.setdefault("reason", prop.get("title"))
        entry.setdefault("date", P.today())
        entry.setdefault("finding", prop["fp"])
        schema = P.schema_for(prop["file"], prop.get("section"))
        op = prop.get("op", "append")
        if op == "append" and prop["file"] == "patches.yml" and P.has_entry(corrections, prop["file"], None, entry):
            # a second patch for one intervention in the same batch: merge it into the first
            op = "replace"
        try:
            block, old_block = P.apply_op(corrections, {**prop, "op": op, "entry": entry})
        except P.ProposalError as e:
            print(f"  skipped {prop['fp']}: {e}")
            continue
        rec = {**prop, "op": op, "entry": entry, "yaml_text": block, "old_text": old_block,
               "status": "proposed", "reject_reason": None}
        errors = n7_errors(wt, prop["file"], str(entry[schema.key]))
        if errors:
            P.undo(corrections, rec)
            print(f"  skipped {prop['fp']}: N7 {'; '.join(errors)}")
            continue
        doc["proposals"].append(rec)
        P.save(wt, doc)
        P.run(["git", "add", f"data/corrections/{prop['file']}", P.PROPOSALS_FILE], cwd=wt)
        msg = (f"qa({prop['check']}): {prop['title']}\n\n{prop.get('message') or ''}\n\n"
               f"QA-Finding: {prop['fp']}\nCo-Authored-By: propose.py <noreply@laciutatparla.es>")
        try:
            P.run(["git", "commit", "-q", "-m", msg], cwd=wt)
        except RuntimeError:
            # leave the branch as it was before this proposal (earlier ones stay committed)
            P.run(["git", "reset", "-q", "--hard", "HEAD"], cwd=wt)
            raise
        added.append(rec)
        print(f"  + {prop['severity']} {prop['fp']} → data/corrections/{prop['file']}")
    return added, overflow


def publish(wt: Path, doc: dict, pr: dict | None) -> str:
    import tempfile
    branch = doc["branch"]
    P.run(["git", "push", "-q", "-u", "origin", branch], cwd=wt)
    if pr:
        P.update_pr_body(wt, pr["number"], doc)
        return pr["url"]
    with tempfile.NamedTemporaryFile("w", suffix=".md", delete=False, encoding="utf-8") as fh:
        fh.write(P.merge_body("", P.render_body(doc)))
    try:
        title = f"QA data corrections · {branch.split('/', 1)[-1]}"
        return P.run(["gh", "pr", "create", "--base", "main", "--head", branch, "--label", "qa-data",
                      "--title", title, "--body-file", fh.name], cwd=wt).splitlines()[-1]
    finally:
        Path(fh.name).unlink(missing_ok=True)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    src = ap.add_mutually_exclusive_group(required=True)
    src.add_argument("--input", type=Path, help="JSON list of verified proposals")
    src.add_argument("--fixture", action="store_true", help="use the built-in example (branch qa/test)")
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--dry-run", action="store_true", help="commit in the worktree, print the PR body, no push")
    mode.add_argument("--push", action="store_true", help="push and open/update the qa-data PR")
    ap.add_argument("--worktree", type=Path, default=None)
    ap.add_argument("--branch", help="override the branch name")
    ap.add_argument("--sparse", action="store_true", help="create the worktree without PDFs and texts (tests)")
    ap.add_argument("--max-per-pr", type=int, default=P.MAX_PER_PR,
                    help=f"live proposals per PR (default {P.MAX_PER_PR}); raise it for a one-off batch that belongs in one PR")
    args = ap.parse_args(argv)

    wt = (args.worktree or default_worktree()).resolve()
    state = state_dir()
    P.run(["git", "fetch", "-q", "origin"], cwd=REPO_ROOT)
    ensure_worktree(wt, args.sparse)
    P.run(["git", "fetch", "-q", "origin"], cwd=wt)

    pr = None if args.dry_run and args.fixture else P.open_data_pr(wt)
    if pr:  # join the one open data PR, whatever it is called
        branch, fresh = pr["headRefName"], False
    else:   # a new data PR: always from origin/main, on a branch name nobody used yet
        base = args.branch or ("qa/test" if args.fixture else f"qa/{dt.date.today():%Y-%m}")
        branch, fresh = free_branch_name(wt, base), True
    checkout_branch(wt, branch, fresh=fresh)

    doc = P.load(wt)
    if fresh or doc.get("branch") != branch:  # main carries the last merged PR's proposals file
        doc = {"branch": branch, "proposals": []}
    incoming = FIXTURE if args.fixture else json.loads(args.input.read_text(encoding="utf-8"))
    queued = [] if args.fixture else load_queue(state)
    added, overflow = add_proposals(wt, doc, queued + incoming, cap=args.max_per_pr)
    save_queue(state, [] if args.fixture else overflow)
    if overflow:
        print(f"  {len(overflow)} proposal(s) over the cap of {args.max_per_pr}: queued in {state / 'queue.jsonl'}")

    if args.dry_run:
        print("\n" + P.render_body(doc))
        print(f"\n(dry run) {len(added)} commit(s) on {branch} in {wt}; nothing pushed")
        return 0
    if not added and pr:
        print("nothing new to add")
        return 0
    url = publish(wt, doc, pr)
    print(f"{'updated' if pr else 'opened'} {url} ({len(P.active(doc))} live proposal(s))")
    return 0


if __name__ == "__main__":
    sys.exit(main())
