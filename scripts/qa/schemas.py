"""Schemas of data/corrections/*.yml, for check N7 (arquitectura-agentes.md §7).

Each schema says how entries are listed, which field identifies an entry, which fields are
required, which must be strings (an unquoted 2025-05-27 parses as a date and never matches
a pleno_id), and what each reference points to.

`reason` and `date` are required only for entries added after the legacy snapshot in
meta/qa/n7_legacy.json (taken when N7 was introduced): about 30 of 42 merges and most
patches have `reason: ''` and none has `date`, and the backlog is F5 work, not a blocker.
"""

from __future__ import annotations

from dataclasses import dataclass, field

VALID_TIPUS = {"av", "plataforma", "ong", "sindical", "cultural", "educacio", "esportiu",
               "empresa", "particular", "altres"}
VALID_IDIOMES = {"valenciano", "castellano"}


@dataclass(frozen=True)
class Schema:
    file: str
    section: str | None          # top-level key holding the list, None if the file is a list
    key: str                     # field that identifies the entry
    required: tuple[str, ...]
    str_fields: tuple[str, ...] = ()       # must be YAML strings (quote dates!)
    list_fields: tuple[str, ...] = ()
    iv_refs: tuple[str, ...] = ()          # must name an existing intervention
    final_iv_refs: tuple[str, ...] = ()    # must name an intervention of the final dataset
    pleno_refs: tuple[str, ...] = ()       # must name a session in sessions_index
    entity_refs: tuple[str, ...] = ()      # should name a catalog entity (else: no effect)
    tipus_field: str | None = None
    needs_reason: bool = True              # reason + date for new entries
    extra: dict = field(default_factory=dict)


SCHEMAS = (
    Schema("deletions.yml", "interventions", "iv_id", ("iv_id",), str_fields=("iv_id",)),
    Schema("deletions.yml", "entities", "entity_id", ("entity_id",), str_fields=("entity_id",)),
    Schema("entity_merges.yml", None, "canonical_id", ("canonical_id", "nom_cas", "nom_val", "match_texts"),
           str_fields=("canonical_id",), list_fields=("match_texts", "exclude_texts"),
           entity_refs=("canonical_id",), tipus_field="tipus"),
    Schema("manual_interventions.yml", None, "id", ("id", "pleno_id", "entitat", "text_original"),
           str_fields=("id", "pleno_id"), pleno_refs=("pleno_id",)),
    Schema("new_entities.yml", None, "id", ("id", "nom_cas", "nom_val", "tipus"),
           str_fields=("id",), entity_refs=("id",), tipus_field="tipus"),
    Schema("patches.yml", None, "iv_id", ("iv_id", "fields"), str_fields=("iv_id",), iv_refs=("iv_id",)),
    Schema("reassignments.yml", None, "iv_id", ("iv_id", "entitat", "entitat_id"),
           str_fields=("iv_id", "entitat_id"), final_iv_refs=("iv_id",),
           extra={"strict_entity_refs": ("entitat_id",)}),
    Schema("session_videos.yml", None, "session_id", ("session_id", "url_video"),
           str_fields=("session_id",), list_fields=("url_videos",), pleno_refs=("session_id",),
           needs_reason=False),  # generated by scrape_video_archive.py, with `rule`
    Schema("skip_plenos.yml", None, "pleno_id", ("pleno_id", "reason"),
           str_fields=("pleno_id",), pleno_refs=("pleno_id",)),
    Schema("text_merges.yml", None, "base_id", ("base_id", "merge_ids"),
           str_fields=("base_id",), list_fields=("merge_ids",), iv_refs=("base_id",)),
    Schema("variant_map_forced.yml", None, "text", ("text", "entity_id"),
           str_fields=("text", "entity_id"), entity_refs=("entity_id",)),
)

CORRECTION_FILES = sorted({s.file for s in SCHEMAS})
